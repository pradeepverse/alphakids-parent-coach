// Bundles the coach's markdown (coach/AGENTS.md + coach/skills/**/SKILL.md) into a TS
// module so the static site can load them into deepagents' in-browser StateBackend.
// Runs automatically before `dev` and `build`. Edit the markdown, not the output.
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const coachDir = path.join(root, "coach");
const outFile = path.join(root, "src", "generated", "coach-files.ts");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])),
  );
  return files.flat();
}

const files = (await walk(coachDir)).filter((f) => f.endsWith(".md")).sort();
const record = {};
for (const f of files) {
  const virtual = "/" + path.relative(coachDir, f).split(path.sep).join("/");
  record[virtual] = (await readFile(f, "utf8")).replace(/\r\n/g, "\n");
}

await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(
  outFile,
  `// AUTO-GENERATED by scripts/bundle-coach.mjs — do not edit. Edit coach/**/*.md instead.\n` +
    `export const COACH_FILES: Record<string, string> = ${JSON.stringify(record, null, 2)};\n`,
);
console.log(`[bundle-coach] ${files.length} markdown files -> src/generated/coach-files.ts`);
